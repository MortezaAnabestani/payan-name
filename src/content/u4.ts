/** خط آرشیو: وضعیت سینی. */
export function trayLineFor(picks: number, done: boolean): string {
  if (done) return "سینی برگردانده شد؛ طعمِ هیچ انتخابی نماند.";
  if (picks === 0) return "صف شام هنوز شروع نشده است.";
  return `سینی: ${picks} قاشق — همان سهمیه، همان مزه.`;
}
